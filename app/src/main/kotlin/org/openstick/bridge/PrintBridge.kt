package org.openstick.bridge

import android.content.Context
import android.os.Build
import android.os.Bundle
import android.os.CancellationSignal
import android.os.FileObserver
import android.os.Handler
import android.os.Looper
import android.os.ParcelFileDescriptor
import android.print.PageRange
import android.print.PrintAttributes
import android.print.PrintDocumentAdapter
import android.print.PrintDocumentInfo
import android.print.PrintManager
import android.util.Log
import java.io.File
import java.io.FileInputStream
import java.io.FileOutputStream

/**
 * Watches /tmp/openstick-print for PDF spool jobs generated by Linux CUPS/apps,
 * and triggers Android PrintManager dialogs.
 */
class PrintBridge(
    private val context: Context,
    private val rootfsDir: File
) {
    companion object {
        private const val TAG = "PrintBridge"
    }

    private val tmpDir: File = if (rootfsDir.name == "tmp") {
        rootfsDir
    } else if (File(rootfsDir.parentFile, "tmp").exists()) {
        File(rootfsDir.parentFile, "tmp")
    } else {
        File(rootfsDir, "tmp")
    }
    private val spoolDir = File(tmpDir, "openstick-print")
    private val mainHandler = Handler(Looper.getMainLooper())
    private var observer: FileObserver? = null

    fun start() {
        spoolDir.mkdirs()

        val obs = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            object : FileObserver(spoolDir, CLOSE_WRITE or MOVED_TO) {
                override fun onEvent(event: Int, path: String?) {
                    checkSpool()
                }
            }
        } else {
            @Suppress("DEPRECATION")
            object : FileObserver(spoolDir.absolutePath, CLOSE_WRITE or MOVED_TO) {
                override fun onEvent(event: Int, path: String?) {
                    checkSpool()
                }
            }
        }

        obs.startWatching()
        observer = obs
        checkSpool()
    }

    fun stop() {
        try {
            observer?.stopWatching()
        } catch (_: Exception) {}
        observer = null
    }

    private fun checkSpool() {
        if (!spoolDir.exists()) return
        val files = spoolDir.listFiles { f -> f.extension.equals("pdf", ignoreCase = true) } ?: return
        for (pdf in files) {
            if (pdf.length() > 0) {
                printPdf(pdf)
            }
        }
    }

    private fun printPdf(pdfFile: File) {
        val jobName = pdfFile.nameWithoutExtension
        mainHandler.post {
            try {
                val printManager = context.getSystemService(Context.PRINT_SERVICE) as? PrintManager ?: return@post
                val adapter = object : PrintDocumentAdapter() {
                    override fun onLayout(
                        oldAttributes: PrintAttributes?,
                        newAttributes: PrintAttributes?,
                        cancellationSignal: CancellationSignal?,
                        callback: LayoutResultCallback?,
                        extras: Bundle?
                    ) {
                        if (cancellationSignal?.isCanceled == true) {
                            callback?.onLayoutCancelled()
                            return
                        }
                        val info = PrintDocumentInfo.Builder("$jobName.pdf")
                            .setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
                            .build()
                        callback?.onLayoutFinished(info, true)
                    }

                    override fun onWrite(
                        pages: Array<out PageRange>?,
                        destination: ParcelFileDescriptor?,
                        cancellationSignal: CancellationSignal?,
                        callback: WriteResultCallback?
                    ) {
                        try {
                            if (destination == null) return
                            FileInputStream(pdfFile).use { input ->
                                FileOutputStream(destination.fileDescriptor).use { output ->
                                    input.copyTo(output)
                                }
                            }
                            callback?.onWriteFinished(arrayOf(PageRange.ALL_PAGES))
                            // Delete printed spool file
                            pdfFile.delete()
                        } catch (e: Exception) {
                            Log.e(TAG, "Write error printing PDF", e)
                            callback?.onWriteFailed(e.message)
                        }
                    }
                }

                printManager.print(jobName, adapter, PrintAttributes.Builder().build())
            } catch (e: Exception) {
                Log.e(TAG, "Failed to launch print job for ${pdfFile.name}", e)
            }
        }
    }
}
